CREATE OR REPLACE FUNCTION cj_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION cj_set_article_changed_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.changed_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS categories_set_updated_at ON categories;
CREATE TRIGGER categories_set_updated_at
  BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION cj_set_updated_at();

DROP TRIGGER IF EXISTS latest_updates_set_updated_at ON latest_updates;
CREATE TRIGGER latest_updates_set_updated_at
  BEFORE UPDATE ON latest_updates
  FOR EACH ROW EXECUTE FUNCTION cj_set_updated_at();

DROP TRIGGER IF EXISTS articles_set_changed_at ON articles;
CREATE TRIGGER articles_set_changed_at
  BEFORE UPDATE ON articles
  FOR EACH ROW EXECUTE FUNCTION cj_set_article_changed_at();

