CREATE TABLE IF NOT EXISTS categories (
  slug VARCHAR(80) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  icon VARCHAR(24) NOT NULL DEFAULT '',
  color VARCHAR(24) NOT NULL DEFAULT 'blue',
  home_visible SMALLINT NOT NULL DEFAULT 1 CHECK (home_visible IN (0, 1)),
  nav_visible SMALLINT NOT NULL DEFAULT 1 CHECK (nav_visible IN (0, 1)),
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_categories_order ON categories (is_active, sort_order, name);

CREATE TABLE IF NOT EXISTS category_home_tabs (
  category_slug VARCHAR(80) NOT NULL REFERENCES categories (slug) ON UPDATE CASCADE ON DELETE CASCADE,
  tab_slug VARCHAR(40) NOT NULL CHECK (tab_slug IN (
    'latest-updates', 'results', 'admit', 'jobs', 'scholarship', 'answer-key', 'syllabus',
    'admission', 'certificate', 'offline-outsourcing-job', 'important'
  )),
  PRIMARY KEY (category_slug, tab_slug)
);

CREATE INDEX IF NOT EXISTS idx_category_home_tabs_tab ON category_home_tabs (tab_slug, category_slug);

CREATE TABLE IF NOT EXISTS admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMP NULL
);

CREATE TABLE IF NOT EXISTS admin_login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_hash CHAR(64) NOT NULL,
  attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  succeeded SMALLINT NOT NULL DEFAULT 0 CHECK (succeeded IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_date ON admin_login_attempts (ip_hash, attempted_at);

CREATE TABLE IF NOT EXISTS api_rate_limits (
  ip_hash CHAR(64) NOT NULL,
  route_name VARCHAR(80) NOT NULL,
  request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0),
  window_started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (ip_hash, route_name)
);

CREATE TABLE IF NOT EXISTS articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(300) NOT NULL,
  slug VARCHAR(180) NOT NULL UNIQUE,
  category_slug VARCHAR(80) NOT NULL REFERENCES categories (slug) ON UPDATE CASCADE ON DELETE RESTRICT,
  short_description VARCHAR(500) NOT NULL DEFAULT '',
  meta_description VARCHAR(320) NOT NULL DEFAULT '',
  keywords VARCHAR(500) NOT NULL DEFAULT '',
  featured_image VARCHAR(2048) NOT NULL DEFAULT '',
  author_name VARCHAR(120) NOT NULL DEFAULT 'Cyber Junction Team',
  status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'unpublished')),
  is_featured SMALLINT NOT NULL DEFAULT 0 CHECK (is_featured IN (0, 1)),
  published_at TIMESTAMP NULL,
  updated_at TIMESTAMP NULL,
  main_content TEXT NOT NULL,
  important_notice TEXT NOT NULL,
  sections JSONB NOT NULL DEFAULT '{}'::jsonb,
  official_notification_url VARCHAR(2048) NOT NULL DEFAULT '',
  apply_online_url VARCHAR(2048) NOT NULL DEFAULT '',
  official_website_url VARCHAR(2048) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_articles_publication ON articles (status, published_at, is_featured);
CREATE INDEX IF NOT EXISTS idx_articles_category ON articles (category_slug, status, published_at);
CREATE INDEX IF NOT EXISTS idx_articles_changed ON articles (changed_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS article_redirects (
  old_slug VARCHAR(180) PRIMARY KEY,
  new_slug VARCHAR(180) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_article_redirect_target ON article_redirects (new_slug);

CREATE TABLE IF NOT EXISTS latest_updates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(300) NOT NULL,
  url VARCHAR(2048) NOT NULL DEFAULT '',
  description VARCHAR(500) NOT NULL DEFAULT '',
  display_date VARCHAR(80) NOT NULL DEFAULT '',
  is_published SMALLINT NOT NULL DEFAULT 1 CHECK (is_published IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_latest_updates_public ON latest_updates (is_published, sort_order, updated_at);

CREATE TABLE IF NOT EXISTS quick_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(300) NOT NULL,
  url VARCHAR(2048) NOT NULL,
  bg_color VARCHAR(24) NOT NULL DEFAULT 'blue'
    CHECK (bg_color IN ('olive', 'blue', 'orange', 'darkred', 'red', 'green', 'pink', 'royalblue', 'purple', 'teal', 'slate')),
  text_color VARCHAR(24) NOT NULL DEFAULT 'white'
    CHECK (text_color IN ('white', 'dark')),
  position_order INTEGER NOT NULL DEFAULT 0 CHECK (position_order >= 0),
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE quick_links DROP CONSTRAINT IF EXISTS quick_links_bg_color_check;
ALTER TABLE quick_links
  ADD CONSTRAINT quick_links_bg_color_check
  CHECK (bg_color IN ('olive', 'blue', 'orange', 'darkred', 'red', 'green', 'pink', 'royalblue', 'purple', 'teal', 'slate'));

CREATE INDEX IF NOT EXISTS idx_quick_links_public ON quick_links (is_active, position_order, id);

CREATE TABLE IF NOT EXISTS homepage_settings (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  content JSONB NOT NULL DEFAULT '{}'::jsonb,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_contact_messages_created ON contact_messages (created_at);

CREATE TABLE IF NOT EXISTS newsletter_subscribers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  subscribed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_created ON newsletter_subscribers (subscribed_at);

