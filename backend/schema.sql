  'latest-updates',
  CASE c.slug
    WHEN 'results' THEN 'results'
    WHEN 'admit' THEN 'admit'
    WHEN 'jobs' THEN 'jobs'
    WHEN 'scholarship' THEN 'scholarship'
    WHEN 'answer-key' THEN 'answer-key'
    WHEN 'syllabus' THEN 'syllabus'
    WHEN 'admission' THEN 'admission'
    WHEN 'certificate' THEN 'certificate'
    WHEN 'offline-outsourcing-job' THEN 'offline-outsourcing-job'
    WHEN 'important' THEN 'important'
    WHEN 'important-links' THEN 'important'
    ELSE NULL
  END
]) AS mapping(tab_slug)
WHERE mapping.tab_slug IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM category_home_tabs AS existing
    WHERE existing.category_slug = c.slug
  );

