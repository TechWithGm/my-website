INSERT INTO quick_links (title, url, bg_color, text_color, position_order, is_active)
SELECT
  LEFT(link.value->>'title', 300),
  LEFT(link.value->>'url', 2048),
  (ARRAY['olive', 'blue', 'orange', 'darkred', 'red', 'green', 'pink', 'royalblue'])[((link.ordinality - 1) % 8 + 1)::INTEGER],
  'white',
  (link.ordinality - 1)::INTEGER,
  CASE WHEN link.ordinality <= 8 THEN 1 ELSE 0 END
FROM homepage_settings AS settings
CROSS JOIN LATERAL jsonb_array_elements(
  CASE
    WHEN jsonb_typeof(settings.content #> '{homeLayout,quickLinks}') = 'array'
      THEN settings.content #> '{homeLayout,quickLinks}'
    ELSE '[]'::jsonb
  END
) WITH ORDINALITY AS link(value, ordinality)
WHERE settings.id = 1
  AND COALESCE(link.value->>'title', '') <> ''
  AND COALESCE(link.value->>'url', '') <> ''
  AND NOT EXISTS (SELECT 1 FROM quick_links);

UPDATE homepage_settings
SET content = jsonb_set(content, '{homeLayout,quickLinks}', '[]'::jsonb, true)
WHERE id = 1
  AND CASE
    WHEN jsonb_typeof(content #> '{homeLayout,quickLinks}') = 'array'
      THEN jsonb_array_length(content #> '{homeLayout,quickLinks}') > 0
    ELSE FALSE
  END
  AND EXISTS (SELECT 1 FROM quick_links);

